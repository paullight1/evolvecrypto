    #[test]
    fn revoke_all_for_user_deactivates_only_target_users_keys() {
        let store = ApiKeyStore::new();
        let target = Uuid::from_u128(0xAAAA);
        let bystander = Uuid::from_u128(0xBBBB);

        add_key_for(&store, target, "t1", true);
        add_key_for(&store, target, "t2", true);
        add_key_for(&store, bystander, "b1", true);

        let revoked = store.revoke_all_for_user(target);
        assert_eq!(revoked, 2, "both target keys should have been revoked");

        assert!(!store.get("t1").unwrap().is_active);
        assert!(!store.get("t2").unwrap().is_active);
        assert!(
            store.get("b1").unwrap().is_active,
            "bystander's key must be untouched"
        );
    }

