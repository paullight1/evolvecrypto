    /// S19 D.7 — verify signature verification is fast enough that per-request
    /// HMAC (no caching) is not a throughput concern. Ignored by default so it
    /// doesn't run on every `cargo test`; invoke with:
    ///
    ///   cargo test -p exchange-api-gateway --release verify_signature_latency -- --ignored --nocapture
    ///
    /// Expected release-mode numbers on Apple M-series: p50 ~2-4 µs,
    /// p99 ~6-10 µs (dominated by HMAC-SHA256 + HashMap lookup + hex decode).
    /// This is well below the order-path cost (~56 µs) and confirms the
    /// Binance/Bybit stance that per-request HMAC verification does not need
    /// caching.
    #[test]
    #[ignore = "perf microbench — run with --release --ignored"]
    fn verify_signature_latency() {
        let store = setup_store();
        let ts = chrono::Utc::now().timestamp_millis().to_string();
        let body = r#"{"symbol":"BTCUSDT","side":"buy","qty":"0.01","price":"50000"}"#;
        let sig = sign("test-secret-123", &ts, "test-api-key", "5000", body);

        for _ in 0..1_000 {
            let _ = store.verify_signature("test-api-key", &ts, "5000", body, &sig);
        }

        const N: usize = 10_000;
        let mut samples: Vec<u64> = Vec::with_capacity(N);
        for _ in 0..N {
            let start = std::time::Instant::now();
            let r = store.verify_signature("test-api-key", &ts, "5000", body, &sig);
            samples.push(start.elapsed().as_nanos() as u64);
            assert!(r.is_ok());
        }
        samples.sort_unstable();
        let p50 = samples[N / 2];
        let p99 = samples[N * 99 / 100];
        let p999 = samples[N * 999 / 1000];

        println!(
            "verify_signature latency: p50={p50}ns p99={p99}ns p999={p999}ns (n={N})"
        );

        // Release-mode generous ceiling — fails loudly on a genuine 10×
        // regression (e.g. accidental linear-scan key lookup).
        assert!(
            p99 < 50_000,
            "verify_signature p99 exceeded 50 µs regression budget: {p99} ns (p50={p50}, p999={p999})"
        );
    }

