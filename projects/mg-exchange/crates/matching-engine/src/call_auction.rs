//! Call auction engine for pre-market price discovery.
//!
//! During the call auction phase, orders are collected in a buffer (not matched
//! immediately). When the auction ends, the engine:
//! 1. Calculates the equilibrium price that maximises matched volume.
//! 2. Matches all eligible orders at that single price.
//! 3. Returns the fills and any unmatched remainder.
//!
//! NOTE: call_auction operates on local Vec<(Price, Qty, usize)>, never touches
//! OrderBook::bids or OrderBook::asks. No best_bid/best_ask cache update hooks
//! are needed here. The auction result is applied to the book separately via
//! standard place_order calls, which go through insert_order and update the cache.

use exchange_common::*;
use rust_decimal::Decimal;
use std::collections::BTreeMap;

/// Result of running a call auction.
#[derive(Debug, Clone)]
pub struct AuctionResult {
    /// The single clearing price.
    pub clearing_price: Price,
    /// Total matched volume.
    pub matched_volume: Qty,
    /// Individual fills generated by the auction.
    pub fills: Vec<AuctionFill>,
    /// Orders (or remainders) that were NOT filled — can be placed on the
    /// continuous book if the pair transitions to active trading.
    pub unmatched: Vec<PlaceOrderCommand>,
}

/// A single fill produced by the auction.
#[derive(Debug, Clone)]
pub struct AuctionFill {
    pub trade_id: TradeId,
    pub symbol: Symbol,
    pub price: Price,
    pub qty: Qty,
    pub maker_order_id: OrderId,
    pub taker_order_id: OrderId,
    pub maker_user_id: UserId,
    pub taker_user_id: UserId,
    /// The taker side — by convention the side of the order that would have
    /// been the aggressor in continuous trading.
    pub taker_side: Side,
}

/// Run a call auction on a set of collected orders.
///
/// Algorithm:
/// 1. Build cumulative bid volume (descending) and ask volume (ascending).
/// 2. For each candidate price, compute `matchable_volume = min(cum_bid, cum_ask)`.
/// 3. Choose the price that maximises matchable volume.
///    Tie-break: closest to `reference_price`, then highest price.
/// 4. Match bids ≥ clearing price against asks ≤ clearing price at clearing price.
pub fn run_auction(
    orders: &[PlaceOrderCommand],
    reference_price: Option<Price>,
    next_trade_id: &mut TradeId,
) -> Option<AuctionResult> {
    if orders.is_empty() {
        return None;
    }

    // Separate into bids and asks with their prices and quantities.
    let mut bids: Vec<(Price, Qty, usize)> = Vec::new(); // (price, qty, original_index)
    let mut asks: Vec<(Price, Qty, usize)> = Vec::new();

    for (i, o) in orders.iter().enumerate() {
        match o.side {
            Side::Buy => bids.push((o.price, o.qty, i)),
            Side::Sell => asks.push((o.price, o.qty, i)),
        }
    }

    if bids.is_empty() || asks.is_empty() {
        return None;
    }

    // Sort bids descending by price (highest first), asks ascending (lowest first).
    bids.sort_by(|a, b| b.0.cmp(&a.0));
    asks.sort_by(|a, b| a.0.cmp(&b.0));

    // Collect all unique candidate prices.
    let mut candidate_prices: BTreeMap<Price, ()> = BTreeMap::new();
    for (p, _, _) in &bids {
        candidate_prices.insert(*p, ());
    }
    for (p, _, _) in &asks {
        candidate_prices.insert(*p, ());
    }

    // For each candidate price, compute matchable volume.
    let mut best_price: Option<Price> = None;
    let mut best_volume = Decimal::ZERO;

    for &price in candidate_prices.keys() {
        // Cumulative bid volume at this price = sum of qty for bids >= price
        let cum_bid: Decimal = bids.iter().filter(|(p, _, _)| *p >= price).map(|(_, q, _)| *q).sum();
        // Cumulative ask volume at this price = sum of qty for asks <= price
        let cum_ask: Decimal = asks.iter().filter(|(p, _, _)| *p <= price).map(|(_, q, _)| *q).sum();

        let matchable = cum_bid.min(cum_ask);

        if matchable > best_volume
            || (matchable == best_volume && matchable > Decimal::ZERO && is_better_tiebreak(price, best_price, reference_price))
        {
            best_volume = matchable;
            best_price = Some(price);
        }
    }

    let clearing_price = best_price?;
    if best_volume == Decimal::ZERO {
        return None;
    }

    // Match orders at the clearing price.
    // Eligible bids: price >= clearing_price, sorted descending (best bid first).
    // Eligible asks: price <= clearing_price, sorted ascending (best ask first).
    let eligible_bids: Vec<(Price, Qty, usize)> = bids
        .into_iter()
        .filter(|(p, _, _)| *p >= clearing_price)
        .collect();
    let eligible_asks: Vec<(Price, Qty, usize)> = asks
        .into_iter()
        .filter(|(p, _, _)| *p <= clearing_price)
        .collect();

    let mut fills = Vec::new();
    let mut remaining_volume = best_volume;
    let symbol = orders[0].symbol.clone();

    // Track remaining qty per order index.
    let mut bid_remaining: Vec<Qty> = eligible_bids.iter().map(|(_, q, _)| *q).collect();
    let mut ask_remaining: Vec<Qty> = eligible_asks.iter().map(|(_, q, _)| *q).collect();

    let mut bi = 0;
    let mut ai = 0;

    while remaining_volume > Decimal::ZERO && bi < eligible_bids.len() && ai < eligible_asks.len() {
        if bid_remaining[bi] == Decimal::ZERO {
            bi += 1;
            continue;
        }
        if ask_remaining[ai] == Decimal::ZERO {
            ai += 1;
            continue;
        }

        let fill_qty = bid_remaining[bi].min(ask_remaining[ai]).min(remaining_volume);
        let (_, _, bid_idx) = eligible_bids[bi];
        let (_, _, ask_idx) = eligible_asks[ai];

        fills.push(AuctionFill {
            trade_id: *next_trade_id,
            symbol: symbol.clone(),
            price: clearing_price,
            qty: fill_qty,
            maker_order_id: orders[ask_idx].order_id,
            taker_order_id: orders[bid_idx].order_id,
            maker_user_id: orders[ask_idx].user_id,
            taker_user_id: orders[bid_idx].user_id,
            taker_side: Side::Buy,
        });
        *next_trade_id += 1;

        bid_remaining[bi] -= fill_qty;
        ask_remaining[ai] -= fill_qty;
        remaining_volume -= fill_qty;
    }

    // Build unmatched orders (full or partial remainders).
    let mut unmatched = Vec::new();
    for (i, (_, _, orig_idx)) in eligible_bids.iter().enumerate() {
        if bid_remaining[i] > Decimal::ZERO {
            let mut cmd = orders[*orig_idx].clone();
            cmd.qty = bid_remaining[i];
            unmatched.push(cmd);
        }
    }
    for (i, (_, _, orig_idx)) in eligible_asks.iter().enumerate() {
        if ask_remaining[i] > Decimal::ZERO {
            let mut cmd = orders[*orig_idx].clone();
            cmd.qty = ask_remaining[i];
            unmatched.push(cmd);
        }
    }
    // Also include orders that were not eligible at all.
    let eligible_bid_indices: std::collections::HashSet<usize> =
        eligible_bids.iter().map(|(_, _, idx)| *idx).collect();
    let eligible_ask_indices: std::collections::HashSet<usize> =
        eligible_asks.iter().map(|(_, _, idx)| *idx).collect();
    for (i, o) in orders.iter().enumerate() {
        if !eligible_bid_indices.contains(&i) && !eligible_ask_indices.contains(&i) {
            unmatched.push(o.clone());
        }
    }

    Some(AuctionResult {
        clearing_price,
        matched_volume: best_volume,
        fills,
        unmatched,
    })
}

/// Convert auction fills into MatchEvent::Fill events for the settlement pipeline.
pub fn fills_to_events(fills: &[AuctionFill], seq_start: SeqNo) -> Vec<MatchEvent> {
    fills
        .iter()
        .enumerate()
        .map(|(i, f)| {
            MatchEvent::Fill(FillEvent {
                trade_id: f.trade_id,
                symbol: f.symbol.clone(),
                price: f.price,
                qty: f.qty,
                maker_order_id: f.maker_order_id,
                taker_order_id: f.taker_order_id,
                maker_user_id: f.maker_user_id,
                taker_user_id: f.taker_user_id,
                taker_side: f.taker_side,
                timestamp: chrono::Utc::now(),
                seq: seq_start + i as u64,
            })
        })
        .collect()
}

/// Compute the indicative (uncrossing) price without actually matching.
pub fn indicative_price(
    orders: &[PlaceOrderCommand],
    reference_price: Option<Price>,
) -> Option<Price> {
    let mut tid = 0u64;
    run_auction(orders, reference_price, &mut tid).map(|r| r.clearing_price)
}

// Tie-break: prefer price closest to reference, then highest.
fn is_better_tiebreak(
    candidate: Price,
    current_best: Option<Price>,
    reference: Option<Price>,
) -> bool {
    let Some(current) = current_best else {
        return true;
    };
    if let Some(ref_p) = reference {
        let dist_new = (candidate - ref_p).abs();
        let dist_old = (current - ref_p).abs();
        if dist_new < dist_old {
            return true;
        }
        if dist_new > dist_old {
            return false;
        }
    }
    // If equidistant (or no reference), prefer higher price.
    candidate > current
}

#[cfg(test)]
mod tests {
    use super::*;
    use rust_decimal_macros::dec;

    fn make_order(side: Side, price: Decimal, qty: Decimal, user_id: u128) -> PlaceOrderCommand {
        PlaceOrderCommand {
            order_id: uuid::Uuid::new_v4(),
            user_id: uuid::Uuid::from_u128(user_id),
            symbol: Symbol::new("BTCUSDT"),
            side,
            order_type: OrderType::Limit,
            time_in_force: TimeInForce::Gtc,
            price,
            qty,
            timestamp: chrono::Utc::now(),
            reduce_only: false,
            expire_at: None,
            position_idx: 0,
            iceberg_qty: None,
            order_link_id: None,
            slippage_tolerance: None,
            close_position: false,
            stp_mode: StpMode::default(),
            request_expire_time: None,
        }
    }

    #[test]
    fn test_empty_auction_returns_none() {
        let mut tid = 1;
        assert!(run_auction(&[], None, &mut tid).is_none());
    }

    #[test]
    fn test_no_overlap_returns_none() {
        let orders = vec![
            make_order(Side::Buy, dec!(100), dec!(1), 1),
            make_order(Side::Sell, dec!(200), dec!(1), 2),
        ];
        let mut tid = 1;
        assert!(run_auction(&orders, None, &mut tid).is_none());
    }

    #[test]
    fn test_simple_cross() {
        let orders = vec![
            make_order(Side::Buy, dec!(105), dec!(10), 1),
            make_order(Side::Sell, dec!(100), dec!(10), 2),
        ];
        let mut tid = 1;
        let result = run_auction(&orders, Some(dec!(100)), &mut tid).unwrap();

        // Both prices are candidates. At 100: cum_bid=10, cum_ask=10 → vol=10.
        // At 105: cum_bid=10, cum_ask=10 → vol=10. Tie-break: closest to ref=100 → 100.
        assert_eq!(result.clearing_price, dec!(100));
        assert_eq!(result.matched_volume, dec!(10));
        assert_eq!(result.fills.len(), 1);
        assert_eq!(result.fills[0].qty, dec!(10));
    }

    #[test]
    fn test_partial_fill_auction() {
        let orders = vec![
            make_order(Side::Buy, dec!(100), dec!(5), 1),
            make_order(Side::Sell, dec!(95), dec!(10), 2),
        ];
        let mut tid = 1;
        let result = run_auction(&orders, None, &mut tid).unwrap();

        assert_eq!(result.matched_volume, dec!(5));
        assert_eq!(result.fills.len(), 1);
        assert_eq!(result.fills[0].qty, dec!(5));
        // Seller has 5 remaining
        assert!(!result.unmatched.is_empty());
    }

    #[test]
    fn test_multiple_orders_price_discovery() {
        let orders = vec![
            make_order(Side::Buy, dec!(110), dec!(3), 1),
            make_order(Side::Buy, dec!(105), dec!(5), 2),
            make_order(Side::Buy, dec!(100), dec!(10), 3),
            make_order(Side::Sell, dec!(95), dec!(4), 4),
            make_order(Side::Sell, dec!(100), dec!(6), 5),
            make_order(Side::Sell, dec!(105), dec!(8), 6),
        ];
        let mut tid = 1;
        let result = run_auction(&orders, Some(dec!(100)), &mut tid).unwrap();

        // At 100: cum_bid = 3+5+10=18, cum_ask = 4+6=10 → vol=10
        // At 105: cum_bid = 3+5=8, cum_ask = 4+6+8=18 → vol=8
        // At 95: cum_bid = 18, cum_ask = 4 → vol=4
        // At 110: cum_bid = 3, cum_ask = 18 → vol=3
        // Best: 100 with vol=10
        assert_eq!(result.clearing_price, dec!(100));
        assert_eq!(result.matched_volume, dec!(10));
    }

    #[test]
    fn test_indicative_price_function() {
        let orders = vec![
            make_order(Side::Buy, dec!(105), dec!(10), 1),
            make_order(Side::Sell, dec!(100), dec!(10), 2),
        ];
        let ip = indicative_price(&orders, Some(dec!(100)));
        assert_eq!(ip, Some(dec!(100)));
    }

    #[test]
    fn test_fills_to_events() {
        let fills = vec![AuctionFill {
            trade_id: 1,
            symbol: Symbol::new("BTCUSDT"),
            price: dec!(100),
            qty: dec!(5),
            maker_order_id: uuid::Uuid::new_v4(),
            taker_order_id: uuid::Uuid::new_v4(),
            maker_user_id: uuid::Uuid::from_u128(1),
            taker_user_id: uuid::Uuid::from_u128(2),
            taker_side: Side::Buy,
        }];
        let events = fills_to_events(&fills, 100);
        assert_eq!(events.len(), 1);
        match &events[0] {
            MatchEvent::Fill(f) => {
                assert_eq!(f.price, dec!(100));
                assert_eq!(f.qty, dec!(5));
                assert_eq!(f.seq, 100);
            }
            _ => panic!("expected Fill event"),
        }
    }
}
