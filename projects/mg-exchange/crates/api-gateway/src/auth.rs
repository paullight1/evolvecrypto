    /// A signature that differs by a single bit must be rejected, even though
    /// we now use constant-time comparison (no timing oracle).
    #[test]
    fn test_hmac_constant_time_wrong_sig_rejected() {
        let store = setup_store();
        let ts = chrono::Utc::now().timestamp_millis().to_string();
        // Produce a valid sig then flip one hex nibble.
        let valid_sig = sign("test-secret-123", &ts, "test-api-key", "5000", "");
        let mut tampered = valid_sig.clone();
        // Flip the first character: '0'->'1', anything else->'0'.
        let first = tampered.remove(0);
        let replacement = if first == '0' { '1' } else { '0' };
        tampered.insert(0, replacement);

        let result = store.verify_signature("test-api-key", &ts, "5000", "", &tampered);
        assert!(
            matches!(result, Err(AuthError::InvalidSignature)),
            "tampered HMAC must be rejected"
        );
    }

