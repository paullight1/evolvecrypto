// ── Permission helper ─────────────────────────────────────────────────────────

/// Returns `true` if the given IP string represents a loopback address (IPv4 or IPv6).
fn is_loopback(ip: &str) -> bool {
    // Parse as IpAddr to correctly handle both "127.0.0.1" and "::1".
    ip.parse::<std::net::IpAddr>()
        .map(|a| a.is_loopback())
        .unwrap_or(false)
}

/// Enforce a permission for a REST handler.
///
/// Behaviour:
/// - `Uuid::nil()` (the unauthenticated default user) is allowed only when
///   `DEV_MODE` or `EXCHANGE_DEV_MODE` is set in the environment AND the request
///   originates from a loopback address (127.0.0.1 or ::1). This prevents the
///   dev-mode bypass from being exploited even if DEV_MODE accidentally leaks to
///   a production deployment.
/// - A real API key (non-nil UUID) is subject to full permission checks via
///   `key_store`.
///
/// Returns `Ok(())` when access is allowed, or an HTTP-ready `Err` tuple that
/// the handler can return directly with `?`.
pub fn require_permission(
    auth: &AuthenticatedUser,
    permission: Permission,
    key_store: &Option<std::sync::Arc<ApiKeyStore>>,
    api_key_header: Option<&str>,
) -> Result<(), (axum::http::StatusCode, axum::Json<serde_json::Value>)> {
    require_permission_with_ip(auth, permission, key_store, api_key_header, None)
}

/// Like [`require_permission`] but accepts an optional caller IP for the
/// DEV_MODE localhost restriction.  Pass `Some(ip_str)` when the request IP is
/// available (e.g. from `ConnectInfo`); pass `None` to fall back to the
/// permissive behaviour (used by tests that don't have a real socket).
pub fn require_permission_with_ip(
    auth: &AuthenticatedUser,
    permission: Permission,
    key_store: &Option<std::sync::Arc<ApiKeyStore>>,
    api_key_header: Option<&str>,
    caller_ip: Option<&str>,
) -> Result<(), (axum::http::StatusCode, axum::Json<serde_json::Value>)> {
    // Nil UUID is the unauthenticated default user injected by Phase 1 middleware.
    // Allow only when DEV_MODE is set AND the request comes from localhost.
    // The localhost restriction prevents the bypass from working if DEV_MODE is
    // accidentally set in a production environment reachable from the internet.
    if auth.0 == Uuid::nil() {
        let dev_mode = std::env::var("DEV_MODE").is_ok() || std::env::var("EXCHANGE_DEV_MODE").is_ok();
        if dev_mode {
            // When an IP is provided, it must be loopback.  When no IP is
            // provided (test environments), allow through.
            let from_localhost = caller_ip.map(is_loopback).unwrap_or(true);
            if from_localhost {
                return Ok(());
            }
            tracing::warn!(
                ?permission,
                ip = ?caller_ip,
                "DEV_MODE nil-user bypass rejected: request not from localhost"
            );
        }
        return Err((
            axum::http::StatusCode::UNAUTHORIZED,
            axum::Json(serde_json::json!({"error": "Authentication required"})),
        ));
    }

    // Real authenticated user: enforce permissions via the key_store.
    let Some(store) = key_store else {
        // No key store configured — allow (open / dev mode).
        return Ok(());
    };

    let Some(key_str) = api_key_header else {
        tracing::warn!(
            user_id = %auth.0,
            ?permission,
            "Permission check: no API key header for non-nil user — denying"
        );
        return Err((
            axum::http::StatusCode::FORBIDDEN,
            axum::Json(serde_json::json!({"error": "Missing API key"})),
        ));
    };

    match store.check_permission(key_str, permission) {
        Ok(()) => Ok(()),
        Err(AuthError::PermissionDenied) => {
            tracing::warn!(
                user_id = %auth.0,
                ?permission,
                "API key lacks required permission"
            );
            Err((
                axum::http::StatusCode::FORBIDDEN,
                axum::Json(serde_json::json!({
                    "error": format!("API key lacks the required permission: {:?}", permission)
                })),
            ))
        }
        Err(e) => {
            tracing::warn!(
                user_id = %auth.0,
                ?permission,
                error = %e,
                "API key permission check failed"
            );
            Err((
                axum::http::StatusCode::UNAUTHORIZED,
                axum::Json(serde_json::json!({"error": e.to_string()})),
            ))
        }
    }
}

// ── Encryption helpers ────────────────────────────────────────────────────────

/// Encrypt an API secret with AES-256-GCM.
/// Returns base64-encoded `nonce || ciphertext`.
pub fn encrypt_secret(plaintext: &str, master_key: &[u8; 32]) -> String {
    use aes_gcm::KeyInit as _;
    let key = Key::<Aes256Gcm>::from_slice(master_key);
    let cipher = Aes256Gcm::new(key);

    let mut nonce_bytes = [0u8; 12];
    OsRng.fill_bytes(&mut nonce_bytes);
    let nonce = Nonce::from_slice(&nonce_bytes);

    let ciphertext = cipher
        .encrypt(nonce, plaintext.as_bytes())
        .expect("AES-GCM encryption should not fail");

    // Prepend nonce to ciphertext so the receiver can split them.
    let mut combined = nonce_bytes.to_vec();
    combined.extend_from_slice(&ciphertext);

    base64::engine::general_purpose::STANDARD.encode(&combined)
}

/// Decrypt an API secret encrypted with AES-256-GCM.
/// Input is base64-encoded `nonce || ciphertext`.
pub fn decrypt_secret(encrypted: &str, master_key: &[u8; 32]) -> Result<String, AuthError> {
    use aes_gcm::KeyInit as _;
    let combined = base64::engine::general_purpose::STANDARD
        .decode(encrypted)
        .map_err(|_| AuthError::InvalidSignature)?;

    if combined.len() < 12 {
        return Err(AuthError::InvalidSignature);
    }

    let (nonce_bytes, ciphertext) = combined.split_at(12);
    let key = Key::<Aes256Gcm>::from_slice(master_key);
    let cipher = Aes256Gcm::new(key);
    let nonce = Nonce::from_slice(nonce_bytes);

    let plaintext = cipher
        .decrypt(nonce, ciphertext)
        .map_err(|_| AuthError::InvalidSignature)?;

    String::from_utf8(plaintext).map_err(|_| AuthError::InvalidSignature)
}

/// Load the master encryption key from the `API_SECRET_ENCRYPTION_KEY` env var.
///
/// Returns `None` if the variable is absent or malformed. The value must be a
/// hex-encoded 32-byte (256-bit) key, i.e. exactly 64 hex characters.
pub fn load_master_key() -> Option<[u8; 32]> {
    let hex_key = std::env::var("API_SECRET_ENCRYPTION_KEY").ok()?;
    let bytes = hex::decode(&hex_key).ok()?;
    if bytes.len() != 32 {
        tracing::error!(
            got = bytes.len(),
            "API_SECRET_ENCRYPTION_KEY must be exactly 32 bytes (64 hex chars)"
        );
        return None;
    }
    let mut key = [0u8; 32];
    key.copy_from_slice(&bytes);
    Some(key)
}

