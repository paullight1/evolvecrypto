// ── Signing method ────────────────────────────────────────────────────────────

/// Signature method used by an API key.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SignType {
    /// HMAC-SHA256 (default). The exchange generates a secret for the user.
    Hmac,
    /// RSA-SHA256. The user provides a PEM public key; the exchange stores it.
    Rsa,
    /// Ed25519. The user provides a base64-encoded 32-byte public key.
    Ed25519,
}

