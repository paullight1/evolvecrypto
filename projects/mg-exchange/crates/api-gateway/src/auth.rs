/// Return a 403 JSON tuple ready for an axum handler `return`.
pub fn forbidden_response() -> (axum::http::StatusCode, axum::Json<serde_json::Value>) {
    (
        axum::http::StatusCode::FORBIDDEN,
        axum::Json(serde_json::json!({"error": "Forbidden"})),
    )
}

// ── Permissions ───────────────────────────────────────────────────────────────

/// Fine-grained permissions attached to an API key.
#[derive(Debug, Clone)]
pub struct ApiKeyPermissions {
    /// Can read market data, account info, order history.
    pub can_read: bool,
    /// Can place and cancel orders.
    pub can_trade: bool,
    /// Can initiate withdrawals.
    pub can_withdraw: bool,
}

impl ApiKeyPermissions {
    /// Read-only key — the safest default.
    pub fn read_only() -> Self {
        Self { can_read: true, can_trade: false, can_withdraw: false }
    }

    /// Trading permissions (read + trade, no withdraw).
    pub fn trading() -> Self {
        Self { can_read: true, can_trade: true, can_withdraw: false }
    }

    /// Full permissions.
    pub fn full() -> Self {
        Self { can_read: true, can_trade: true, can_withdraw: true }
    }
}

/// Permission being checked.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Permission {
    Read,
    Trade,
    Withdraw,
}

// ── API Key ───────────────────────────────────────────────────────────────────

/// API key record.
#[derive(Debug, Clone)]
pub struct ApiKey {
    pub key: String,
    /// For `SignType::Hmac`: the HMAC secret (generated by exchange).
    /// For `SignType::Rsa` and `SignType::Ed25519`: empty — the public key is
    /// stored in `public_key` instead.
    pub secret: String,
    pub user_id: Uuid,
    pub label: String,
    pub permissions: ApiKeyPermissions,
    /// Allowed source IPs. Empty means any IP is accepted.
    pub allowed_ips: Vec<String>,
    pub created_at: chrono::DateTime<chrono::Utc>,
    pub is_active: bool,
    /// Admin role attached to this key. `None` means the key is a regular user key
    /// with no access to `/admin/*` endpoints. Any `Some(role)` grants admin access
    /// and further scopes it by the role's permissions.
    pub admin_role: Option<AdminRole>,
    /// Signature method for this key. Defaults to `SignType::Hmac`.
    pub sign_type: SignType,
    /// For `SignType::Rsa`: PEM-encoded RSA public key supplied by the user.
    /// For `SignType::Ed25519`: base64-encoded 32-byte public key supplied by
    /// the user.
    /// `None` for `SignType::Hmac` keys.
    pub public_key: Option<String>,
}

// ── Store ─────────────────────────────────────────────────────────────────────

/// API key store — maps api_key string to ApiKey record.
///
/// Phase 1: in-memory HashMap.
/// Phase 2: PostgreSQL lookup with Redis cache.
pub struct ApiKeyStore {
    keys: RwLock<HashMap<String, ApiKey>>,
}

impl ApiKeyStore {
    pub fn new() -> Self {
        Self {
            keys: RwLock::new(HashMap::new()),
        }
    }

    /// Register a new API key.
    pub fn add_key(&self, key: ApiKey) {
        self.keys.write().unwrap_or_else(|e| e.into_inner()).insert(key.key.clone(), key);
    }

    /// Look up an API key. Returns None if not found.
    pub fn get(&self, api_key: &str) -> Option<ApiKey> {
        self.keys.read().unwrap_or_else(|e| e.into_inner()).get(api_key).cloned()
    }

    /// Check whether an API key has the required permission.
    pub fn check_permission(&self, api_key: &str, permission: Permission) -> Result<(), AuthError> {
        let key = self.get(api_key).ok_or(AuthError::InvalidApiKey)?;

        if !key.is_active {
            return Err(AuthError::InvalidApiKey);
        }

        let allowed = match permission {
            Permission::Read => key.permissions.can_read,
            Permission::Trade => key.permissions.can_trade,
            Permission::Withdraw => key.permissions.can_withdraw,
        };

        if allowed { Ok(()) } else { Err(AuthError::PermissionDenied) }
    }

    /// Check whether the given IP address is allowed for this API key.
    ///
    /// An empty `allowed_ips` list means any IP is permitted.
    pub fn check_ip(&self, api_key: &str, ip: &str) -> Result<(), AuthError> {
        let key = self.get(api_key).ok_or(AuthError::InvalidApiKey)?;

        if key.allowed_ips.is_empty() || key.allowed_ips.iter().any(|a| a == ip) {
            Ok(())
        } else {
            Err(AuthError::IpNotAllowed)
        }
    }

    /// Verify HMAC signature.
    ///
    /// Signature scheme (compatible with Bybit/Binance style):
    /// ```text
    /// signature = HMAC-SHA256(secret, timestamp + api_key + recv_window + body)
    /// ```
    ///
    /// Headers required:
    /// - X-API-Key: the public API key
    /// - X-API-Timestamp: Unix timestamp in milliseconds
    /// - X-API-Sign: hex-encoded HMAC signature
    /// - X-API-Recv-Window: (optional) max age in ms, default 5000
    pub fn verify_signature(
        &self,
        api_key: &str,
        timestamp: &str,
        recv_window: &str,
        body: &str,
        signature: &str,
    ) -> Result<Uuid, AuthError> {
        let key_record = self.get(api_key).ok_or(AuthError::InvalidApiKey)?;

        // Build sign string
        let sign_payload = format!("{}{}{}{}", timestamp, api_key, recv_window, body);

        // Compute HMAC and compare in constant time to prevent timing attacks.
        let mut mac =
            HmacSha256::new_from_slice(key_record.secret.as_bytes()).map_err(|_| AuthError::InvalidSignature)?;
        mac.update(sign_payload.as_bytes());

        // Decode the hex signature from the request before constant-time comparison.
        let sig_bytes = hex::decode(signature).map_err(|_| AuthError::InvalidSignature)?;

        // `verify_slice` uses a constant-time comparison internally (via `subtle` crate).
        mac.verify_slice(&sig_bytes).map_err(|_| AuthError::InvalidSignature)?;

        // Check timestamp freshness
        let ts: i64 = timestamp.parse().map_err(|_| AuthError::InvalidTimestamp)?;
        let now = chrono::Utc::now().timestamp_millis();
        let window: i64 = recv_window.parse().unwrap_or(5000);

        if (now - ts).abs() > window {
            return Err(AuthError::TimestampExpired);
        }

        Ok(key_record.user_id)
    }

    /// List all API keys belonging to a user (active and inactive).
    pub fn list_user_keys(&self, user_id: Uuid) -> Vec<ApiKey> {
        self.keys
            .read().unwrap_or_else(|e| e.into_inner())
            .values()
            .filter(|k| k.user_id == user_id)
            .cloned()
            .collect()
    }

    /// Return `true` if the given key exists, is active, and has any admin role.
    pub fn is_admin_key(&self, api_key: &str) -> bool {
        self.keys
            .read().unwrap_or_else(|e| e.into_inner())
            .get(api_key)
            .map(|k| k.is_active && k.admin_role.is_some())
            .unwrap_or(false)
    }

    /// Check that the given API key holds a specific admin permission.
    ///
    /// Returns the resolved `AdminRole` on success, or an HTTP-ready error tuple on
    /// failure. Intended for use inside axum handlers:
    ///
    /// ```no_run
    /// # use exchange_api_gateway::auth::ApiKeyStore;
    /// # use exchange_common::AdminPermission;
    /// # fn example(store: &ApiKeyStore, api_key_header: Option<&str>)
    /// #    -> Result<(), (axum::http::StatusCode, axum::Json<serde_json::Value>)> {
    /// let role = store.check_admin_permission(api_key_header, AdminPermission::KycApprove)?;
    /// # let _ = role;
    /// # Ok(())
    /// # }
    /// ```
    pub fn check_admin_permission(
        &self,
        api_key: Option<&str>,
        required: AdminPermission,
    ) -> Result<AdminRole, (axum::http::StatusCode, axum::Json<serde_json::Value>)> {
        let key_str = api_key.ok_or_else(|| {
            (
                axum::http::StatusCode::UNAUTHORIZED,
                axum::Json(serde_json::json!({"error": "Missing API key"})),
            )
        })?;

        let key = self.get(key_str).ok_or_else(|| {
            (
                axum::http::StatusCode::UNAUTHORIZED,
                axum::Json(serde_json::json!({"error": "Invalid API key"})),
            )
        })?;

        let role = key.admin_role.ok_or_else(|| {
            (
                axum::http::StatusCode::FORBIDDEN,
                axum::Json(serde_json::json!({"error": "Not an admin"})),
            )
        })?;

        if !role.has_permission(required) {
            return Err((
                axum::http::StatusCode::FORBIDDEN,
                axum::Json(serde_json::json!({
                    "error": format!("Insufficient permissions. Required: {:?}", required)
                })),
            ));
        }

        Ok(role)
    }

    /// Verify a request signature, dispatching on the key's `sign_type`.
    ///
    /// The `sign_type_header` is the value of `X-API-Sign-Type`; when absent
    /// the method falls back to the sign type recorded on the key itself
    /// (defaulting to HMAC).
    ///
    /// The signed payload is: `timestamp + api_key + recv_window + body`
    /// (same convention as HMAC, so clients can reuse their payload builder).
    pub fn verify_signature_typed(
        &self,
        api_key: &str,
        timestamp: &str,
        recv_window: &str,
        body: &str,
        signature: &str,
        sign_type_header: Option<&str>,
    ) -> Result<Uuid, AuthError> {
        let key_record = self.get(api_key).ok_or(AuthError::InvalidApiKey)?;

        // Check timestamp freshness first — applies to all sign types.
        let ts: i64 = timestamp.parse().map_err(|_| AuthError::InvalidTimestamp)?;
        let now = chrono::Utc::now().timestamp_millis();
        let window: i64 = recv_window.parse().unwrap_or(5000);
        if (now - ts).abs() > window {
            return Err(AuthError::TimestampExpired);
        }

        // Determine sign type: header overrides the stored key sign_type.
        let effective_sign_type = match sign_type_header {
            Some("rsa")     => SignType::Rsa,
            Some("ed25519") => SignType::Ed25519,
            Some("hmac") | None => key_record.sign_type,
            Some(_) => return Err(AuthError::InvalidSignature),
        };

        let sign_payload = format!("{}{}{}{}", timestamp, api_key, recv_window, body);

        match effective_sign_type {
            SignType::Hmac => {
                // Standard HMAC-SHA256 path — identical to verify_signature.
                let mut mac = HmacSha256::new_from_slice(key_record.secret.as_bytes())
                    .map_err(|_| AuthError::InvalidSignature)?;
                mac.update(sign_payload.as_bytes());
                let sig_bytes = hex::decode(signature).map_err(|_| AuthError::InvalidSignature)?;
                mac.verify_slice(&sig_bytes).map_err(|_| AuthError::InvalidSignature)?;
            }
            SignType::Rsa => {
                // RSA-SHA256: verify PKCS#1 v1.5 or PSS signature.
                // The user base64-encoded their RSA signature; we decode it and
                // verify against the stored public key using the `rsa` crate.
                let pub_key_pem = key_record.public_key.as_deref()
                    .ok_or(AuthError::InvalidSignature)?;
                let sig_bytes = base64::engine::general_purpose::STANDARD
                    .decode(signature)
                    .map_err(|_| AuthError::InvalidSignature)?;
                verify_rsa_sha256(pub_key_pem, sign_payload.as_bytes(), &sig_bytes)?;
            }
            SignType::Ed25519 => {
                let pub_key_b64 = key_record.public_key.as_deref()
                    .ok_or(AuthError::InvalidSignature)?;
                let sig_bytes = base64::engine::general_purpose::STANDARD
                    .decode(signature)
                    .map_err(|_| AuthError::InvalidSignature)?;
                verify_ed25519(pub_key_b64, sign_payload.as_bytes(), &sig_bytes)?;
            }
        }

        Ok(key_record.user_id)
    }

    /// Revoke (deactivate) an API key, enforcing that the caller owns it.
    pub fn revoke_key(&self, api_key: &str, owner_id: Uuid) -> Result<(), AuthError> {
        let mut keys = self.keys.write().unwrap_or_else(|e| e.into_inner());
        let key = keys.get_mut(api_key).ok_or(AuthError::InvalidApiKey)?;

        if key.user_id != owner_id {
            return Err(AuthError::InvalidApiKey);
        }

        key.is_active = false;
        Ok(())
    }

    /// Admin path: deactivate every active key belonging to `user_id`.
    ///
    /// Returns the number of keys that transitioned from active to inactive.
    /// Already-inactive keys are left alone and not counted. This is the
    /// operation invoked by `DELETE /admin/users/{user_id}/api-keys` during
    /// a suspected-breach incident.
    pub fn revoke_all_for_user(&self, user_id: Uuid) -> usize {
        let mut keys = self.keys.write().unwrap_or_else(|e| e.into_inner());
        let mut revoked = 0;
        for key in keys.values_mut() {
            if key.user_id == user_id && key.is_active {
                key.is_active = false;
                revoked += 1;
            }
        }
        revoked
    }
}

impl Default for ApiKeyStore {
    fn default() -> Self {
        Self::new()
    }
}

// ── Crypto verification helpers ───────────────────────────────────────────────

/// Verify an RSA-SHA256 signature.
///
/// `pub_key_pem`: PEM-encoded RSA public key (PKCS#8 SubjectPublicKeyInfo or
/// traditional PKCS#1 format).
/// `message`: the signed payload bytes.
/// `signature`: raw (binary) signature bytes — NOT base64 at this point.
///
/// Returns `Ok(())` on success or `Err(AuthError::InvalidSignature)`.
fn verify_rsa_sha256(pub_key_pem: &str, message: &[u8], signature: &[u8]) -> Result<(), AuthError> {
    use sha2::Digest;
    use rsa::pkcs1::DecodeRsaPublicKey;
    use rsa::pkcs8::DecodePublicKey;

    // Parse the PEM-encoded public key: try PKCS#8 first, fall back to PKCS#1.
    let pub_key = rsa::RsaPublicKey::from_public_key_pem(pub_key_pem)
        .or_else(|_| rsa::RsaPublicKey::from_pkcs1_pem(pub_key_pem))
        .map_err(|_| AuthError::InvalidSignature)?;

    // Hash the message with SHA-256.
    let digest = sha2::Sha256::digest(message);

    // Verify PKCS#1 v1.5 signature.
    use rsa::pkcs1v15::Pkcs1v15Sign;
    pub_key
        .verify(Pkcs1v15Sign::new::<sha2::Sha256>(), &digest, signature)
        .map_err(|_| AuthError::InvalidSignature)
}

/// Verify an Ed25519 signature.
///
/// `pub_key_b64`: base64-encoded 32-byte Ed25519 public key.
/// `message`: the signed payload bytes.
/// `signature`: raw 64-byte signature (binary, already decoded from base64 by
/// the caller).
fn verify_ed25519(pub_key_b64: &str, message: &[u8], signature: &[u8]) -> Result<(), AuthError> {
    use ed25519_dalek::{Signature, Verifier, VerifyingKey};

    let key_bytes = base64::engine::general_purpose::STANDARD
        .decode(pub_key_b64)
        .map_err(|_| AuthError::InvalidSignature)?;

    let key_arr: [u8; 32] = key_bytes.try_into().map_err(|_| AuthError::InvalidSignature)?;
    let verifying_key = VerifyingKey::from_bytes(&key_arr)
        .map_err(|_| AuthError::InvalidSignature)?;

    let sig_arr: [u8; 64] = signature.try_into().map_err(|_| AuthError::InvalidSignature)?;
    let sig = Signature::from_bytes(&sig_arr);

    verifying_key
        .verify(message, &sig)
        .map_err(|_| AuthError::InvalidSignature)
}

// ── Errors ────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AuthError {
    MissingHeaders,
    InvalidApiKey,
    InvalidSignature,
    InvalidTimestamp,
    TimestampExpired,
    /// The key exists but lacks the required permission.
    PermissionDenied,
    /// The request came from an IP not on the key's allowlist.
    IpNotAllowed,
}

impl std::fmt::Display for AuthError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AuthError::MissingHeaders => write!(f, "Missing authentication headers"),
            AuthError::InvalidApiKey => write!(f, "Invalid API key"),
            AuthError::InvalidSignature => write!(f, "Invalid signature"),
            AuthError::InvalidTimestamp => write!(f, "Invalid timestamp"),
            AuthError::TimestampExpired => write!(f, "Request timestamp expired"),
            AuthError::PermissionDenied => write!(f, "API key lacks the required permission"),
            AuthError::IpNotAllowed => write!(f, "Request IP is not on the allowed list"),
        }
    }
}

